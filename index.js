const dia = "domingo";

switch (dia){
    case "Segunda":
        console.log("Segunda-feira");
        break;
    case "Terça":
        console.log("Terça-feira");
        break;
    case "Quarta":
        console.log("Quarta-feira");
        break;
    case "Quinta":
        console.log("Quinta-feira");
        break;
    case "Sexta":
        console.log("Sexta-feira");
        break;
    case "Sábado":
        console.log("Sábado sem feira kkkk");
        break;
    default:
        console.log("Valor inexistente!");
}